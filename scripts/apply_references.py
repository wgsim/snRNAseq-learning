#!/usr/bin/env python3
"""
apply_references.py  (standard library only)
Writes the generated reference block at the end of a source chapter from review/refs/<prefix>_<chapter>.ids.

  python3 scripts/apply_references.py                 # apply to every .ids file (idempotent: replaces the block)
  python3 scripts/apply_references.py review/refs/docs_03_QC_AND_CLEANING.ids [...]
  python3 scripts/apply_references.py --check [files]  # byte-compare chapter blocks with the rebuilt ones

.ids format: sections [cited] [evidence] [software]; one ID per line (PMID:.., DOI:.., SW:key); '#' starts a comment.
  prefix 'docs' -> docs/<chapter>.md ; any other prefix is a track directory name -> tracks/<prefix>/docs/<chapter>.md
  IDs in [cited] and [evidence] at once are kept in [cited] only. SW keys must exist in review/software_refs.json.
References come only from format_references.py output via the offline cache (review/references_cache.json);
an ID missing from the cache is an error (look it up first with scripts/format_references.py).
"""
import glob, os, re, sys, importlib.util

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_spec = importlib.util.spec_from_file_location("format_references", os.path.join(ROOT, "scripts", "format_references.py"))
fr = importlib.util.module_from_spec(_spec); _spec.loader.exec_module(fr)

BEGIN = "<!-- REFERENCES:BEGIN (generated by scripts/apply_references.py; do not edit by hand) -->"
END = "<!-- REFERENCES:END -->"
BLOCK_RE = re.compile(r"(?:\n---\n\n)?" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.S)
HEAD = {"cited": "### 본문 인용 문헌", "evidence": "### 검수 근거 문헌", "software": "### 소프트웨어 (표기 버전은 검수 시 API를 확인한 버전이며, 파이프라인 실행 환경은 requirements-pipelines.txt 참조)"}


def chapter_path(ids_path):
    stem = os.path.basename(ids_path)[:-4]
    if stem.startswith("docs_"):
        return os.path.join("docs", stem[5:] + ".md")
    for t in sorted(os.listdir(os.path.join(ROOT, "tracks"))):
        if stem.startswith(t + "_"):
            return os.path.join("tracks", t, "docs", stem[len(t) + 1:] + ".md")
    raise ValueError(f"cannot map {ids_path} to a chapter")


def parse_ids(path):
    sec, out = None, {"cited": [], "evidence": [], "software": []}
    for line in open(path, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line:
            continue
        m = re.fullmatch(r"\[(cited|evidence|software)\]", line)
        if m:
            sec = m.group(1); continue
        if sec is None:
            raise ValueError(f"{path}: ID before any [section]: {line}")
        out[sec].append(line)
    out["evidence"] = [x for x in out["evidence"] if x not in out["cited"]]
    return out


def build_block(ids_path):
    ids = parse_ids(ids_path)
    cache, sw = fr.load_json(fr.CACHE, {}), fr.load_json(fr.SWREFS, {})

    def get(kind, key):
        ck = f"{kind}:{key}"
        if ck not in cache:
            raise LookupError(f"{ck} not in cache; run scripts/format_references.py first")
        return cache[ck]

    parts = [BEGIN, "## 참고문헌 (References)"]
    for sec in ("cited", "evidence", "software"):
        if not ids[sec]:
            continue
        for x in ids[sec]:
            if sec == "software" and not x.upper().startswith("SW:"):
                raise ValueError(f"{ids_path}: [software] accepts SW:<key> only: {x}")
            if sec != "software" and x.upper().startswith("SW:"):
                raise ValueError(f"{ids_path}: SW: entries belong to [software]: {x}")
        parts.append(HEAD[sec])
        lines = [fr.format_id(x, get, sw) for x in ids[sec]]
        parts += [f"- {l}" for l in lines] if sec == "software" else [f"{i}. {l}" for i, l in enumerate(lines, 1)]
    parts.append(END)
    return "\n".join(parts) + "\n"


def with_block(text, block):
    text = BLOCK_RE.sub("", text).rstrip("\n") + "\n"
    return text + "\n---\n\n" + block


def check_chapter(chapter_rel, ids_path=None):
    """Return ('ok'|'mismatch'|'missing'|'orphan', message). Used by precommit_checks.py."""
    ids_path = ids_path or os.path.join(ROOT, "review", "refs",
        (chapter_rel.replace("tracks/", "").replace("/docs/", "_") if chapter_rel.startswith("tracks/") else "docs_" + os.path.basename(chapter_rel))[:-3] + ".ids")
    text = open(os.path.join(ROOT, chapter_rel), encoding="utf-8").read()
    has = BEGIN in text
    if not os.path.exists(ids_path):
        return ("orphan", "reference block without .ids file") if has else ("missing", "no reference block / .ids file")
    if not has:
        return "missing", "has .ids but the chapter has no reference block (run scripts/apply_references.py)"
    if with_block(text, build_block(ids_path)) != text:
        return "mismatch", "reference block differs from review/refs ids + cache (hand edit? run scripts/apply_references.py)"
    return "ok", ""


def main(argv):
    check = "--check" in argv
    files = [a for a in argv if not a.startswith("--")] or sorted(glob.glob(os.path.join(ROOT, "review", "refs", "*.ids")))
    bad = 0
    for f in files:
        f = os.path.abspath(f)
        try:
            ch = chapter_path(f)
            if check:
                st, msg = check_chapter(ch, f)
                print(f"[{'OK' if st == 'ok' else 'FAIL'}] {ch} {msg}"); bad += st != "ok"
            else:
                p = os.path.join(ROOT, ch)
                text = open(p, encoding="utf-8").read()
                new = with_block(text, build_block(f))
                if new != text:
                    open(p, "w", encoding="utf-8").write(new)
                print(f"[{'updated' if new != text else 'unchanged'}] {ch}")
        except Exception as e:
            print(f"[ERROR] {os.path.basename(f)}: {type(e).__name__}: {e}", file=sys.stderr); bad += 1
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
